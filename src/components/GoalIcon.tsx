type Props = { name: string; size?: number; color: string; strokeWidth?: number };

/** Icono de una meta. Acepta claves antiguas (p. ej. "book") y cae en una estrella si no existe. */
export function GoalIcon({ name, size = 22, color, strokeWidth = 2 }: Props) {
  const Component = COMPONENTS[resolveIconKey(name)] ?? COMPONENTS.star;
  return <Component size={size} color={color} strokeWidth={strokeWidth} />;
}
